"""Declarative base and shared column conventions for the data model.

Every model in this package inherits :class:`Base`, so there is one
``MetaData`` for Alembic to compare against the live database.
"""

from datetime import datetime
from typing import Any
from uuid import UUID

from sqlalchemy import DateTime, MetaData, Uuid, func, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

#: Deterministic names for every constraint and index.
#:
#: Without this, Postgres assigns names like ``documents_uploaded_by_fkey`` and
#: unnamed CHECK constraints get auto-generated names that differ between
#: databases. Alembic then cannot reliably drop what it created, which makes a
#: migration downgrade fail on some machines and pass on others. The migration
#: round-trip test in the suite depends on this being in place.
NAMING_CONVENTION: dict[str, str] = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Declarative base carrying the shared metadata and naming convention."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def uuid_primary_key() -> Mapped[UUID]:
    """A ``uuid`` primary key generated by the database.

    ``gen_random_uuid()`` is a core function in the supported Postgres version,
    so no extension is required. Generating it in the database rather than in
    Python means a row inserted by a migration, a psql session, or a future
    service written in another language gets its id from the same authority, and
    an API client can never supply one.
    """
    return mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
        server_default=text("gen_random_uuid()"),
    )


def created_timestamp(*, index: bool = False) -> Mapped[datetime]:
    """A non-null ``timestamptz`` defaulting to the transaction's start time.

    ``now()`` is transaction-scoped in Postgres, so every row written in one
    transaction shares a timestamp. That is the wanted behavior here: a
    classification and the audit entry proving it happened are one atomic event
    and should not appear microseconds apart.

    Args:
        index: Whether to index the column. Set it for the columns that recency
            queries filter on, per ``docs/data-dictionary.md``.
    """
    return mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        index=index,
    )


def jsonb_column(**kwargs: Any) -> Mapped[dict[str, Any]]:
    """A non-null ``jsonb`` column.

    Used in exactly the three places ``docs/data-dictionary.md`` names. Reach for
    a typed column anywhere else; ``jsonb`` everywhere is easy to write and hard
    to query or trust.
    """
    return mapped_column(JSONB, nullable=False, **kwargs)
